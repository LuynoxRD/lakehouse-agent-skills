def write(path: Path, text: str) -> Path:
    """Create parent directories and write UTF-8 text with LF endings."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    return path


def manifest(version: str, *, name: str = "lakehouse-agent-skills") -> str:
    return json.dumps(
        {
            "name": name,
            "version": version,
            "description": "Data-engineering discipline skills for AI coding agents.",
            "skills": "./skills",
        },
        indent=2,
    )


def marketplace(version: str, *, name: str = "lakehouse-agent-skills") -> str:
    return json.dumps(
        {
            "name": "lakehouse-skills",
            "owner": {"name": "Maintainer"},
            "plugins": [
                {
                    "name": name,
                    "version": version,
                    "source": "./",
                    "description": "Data-engineering discipline skills for AI coding agents.",
                }
            ],
        },
        indent=2,
    )


def pyproject(version: str) -> str:
    return f'[project]\nname = "lakehouse-agent-skills"\nversion = "{version}"\n'


def build_repo(root: Path, *, version: str = "0.1.0") -> Layout:
    """Write a complete repository that passes every validator."""
    layout = Layout(root)
    reference = "data-quality-checklist.md"
    write(
        layout.skills / SKILL_A / "SKILL.md",
        skill_markdown(SKILL_A, DESCRIPTION_A, reference=reference),
    )
    write(
        layout.skills / SKILL_B / "SKILL.md",
        skill_markdown(SKILL_B, DESCRIPTION_B, reference=reference),
    )
    write(layout.references / reference, "# Data quality checklist\n\n- [ ] Types inferred.\n")
    write(
        layout.eval_cases / f"{SKILL_A}.json", case_json(SKILL_A, SKILL_B, f"{SKILL_A}/sales.csv")
    )
    write(
        layout.eval_cases / f"{SKILL_B}.json", case_json(SKILL_B, SKILL_A, f"{SKILL_B}/limits.csv")
    )
    write(layout.eval_fixtures / SKILL_A / "FIXTURE.md", FIXTURE_NOTE)
    write(layout.eval_fixtures / SKILL_A / "sales.csv", 'order_date,amount\n03/04/2025,"1,5"\n')
    write(layout.eval_fixtures / SKILL_B / "FIXTURE.md", FIXTURE_NOTE)
    write(layout.eval_fixtures / SKILL_B / "limits.csv", "sheet,rows\nq1,1048576\n")
    write(
        layout.eval_config,
        json.dumps({"min_rank1_percent": 0, "collision_error": 0.75, "collision_warning": 0.5}),
    )
    write(root / "plugin.json", manifest(version))
    write(root / ".claude-plugin" / "plugin.json", manifest(version))
    write(root / ".claude-plugin" / "marketplace.json", marketplace(version))
    write(root / ".codex-plugin" / "plugin.json", manifest(version))
    write(root / "pyproject.toml", pyproject(version))
    write(layout.commands / "profile.toml", COMMAND_TOML)
    write(
        layout.claude_commands / "profile.md",
        "---\ndescription: Profile a dataset before cleaning or charting it.\n"
        "context: fork\nbackground: false\n---\n\n"
        "Invoke the `etl-before-dashboard` skill and write `docs/data/profile.md`.\n",
    )
    write(layout.gemini_commands / "profile.toml", COMMAND_TOML)
    write(
        layout.docs / "skill-anatomy.md",
        "# Skill anatomy\n\nSee [contributing](../CONTRIBUTING.md).\n",
    )
    write(root / "CONTRIBUTING.md", "# Contributing\n")
    write(root / "README.md", "# Test repo\n")
    return layout


@pytest.fixture
def repo(tmp_path: Path) -> Layout:
    """A valid miniature repository."""
    return build_repo(tmp_path / "repo")
