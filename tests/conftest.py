"""Shared fixtures: a complete, valid miniature repository that tests mutate to provoke findings."""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from lib.repo import Layout

SKILL_A = "etl-before-dashboard"
SKILL_B = "honest-data-limits-disclosure"
DESCRIPTION_A = (
    "Enforces the profile, clean, model, persist, visualize order for tabular data so charts "
    "never render raw ingest. Use when a task asks to chart, dashboard or analyze a CSV, "
    "spreadsheet or parquet file that has not been profiled and cleaned yet."
)
DESCRIPTION_B = (
    "Discloses memory limits, sampling, row caps and unprocessed sheets or files before and "
    "after data work so results never claim more coverage than they have. Use when a dataset "
    "may exceed available memory, when only a sample was read, or when reporting what was "
    "processed."
)


def skill_markdown(name: str, description: str, *, reference: str | None = None) -> str:
    """A SKILL.md that satisfies every rule."""
    title = name.replace("-", " ").title()
    reference_line = (
        f"See the shared checklist in [data quality](../../references/{reference})."
        if reference
        else ""
    )
    return f"""---
name: {name}
description: {description}
---

# {title}

## Overview

Profiling comes first, cleaning second, charts last. {reference_line}

## When to Use

Use this skill when a dataset arrives as a file. Do not use it for streaming pipelines.

## Core Process

### Step 1: Profile

Write the profile to `docs/data/profile.md` before touching a row.

### Step 2: Clean

Persist the result to `data/clean/` and record every rule in `docs/data/cleaning-log.md`.
Step 1 always precedes Step 2.

## Common Rationalizations

| Excuse | Reality |
| --- | --- |
| "It's a quick chart" | Quick charts of raw ingest become the report of record. |

## Red Flags

- A chart spec appears before a profile note exists.

## Verification

- [ ] `docs/data/profile.md` exists and names every column type.
- [ ] Curated parquet lives under `data/curated/`.
"""


def case_json(skill: str, owner: str, fixture: str) -> str:
    """An eval case that satisfies the minimums."""
    return json.dumps(
        {
            "skill_name": skill,
            "trigger": {
                "positive": [
                    {"prompt": f"Prompt one for {skill.replace('-', ' ')}", "top_k": 3},
                    {"prompt": f"Prompt two for {skill.replace('-', ' ')}"},
                    {"prompt": f"Prompt three for {skill.replace('-', ' ')}"},
                ],
                "negative": [
                    {"prompt": f"Prompt that belongs to {owner.replace('-', ' ')}", "owner": owner},
                    {"prompt": f"Another prompt for {owner.replace('-', ' ')}", "owner": owner},
                ],
            },
            "evals": [
                {
                    "id": 1,
                    "kind": "execution",
                    "prompt": "Profile then chart the sales file.",
                    "expected_output": "A profile note, a cleaning log and a chart spec.",
                    "files": [fixture],
                    "expectations": [
                        "The agent writes docs/data/profile.md before any chart.",
                        "The agent discloses row counts it did not process.",
                    ],
                }
            ],
        },
        indent=2,
    )


